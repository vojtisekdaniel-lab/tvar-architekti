def area2(pts):
    s = 0
    for i in range(len(pts)):
        x1, y1 = pts[i]; x2, y2 = pts[(i+1) % len(pts)]
        s += x1*y2 - x2*y1
    return s

def canon(pts):
    """clockwise (screen coords, y down), start at top-left vertex whose outgoing edge is horizontal, no collinear vertices."""
    # remove collinear
    changed = True
    while changed:
        changed = False
        n = len(pts)
        for i in range(n):
            p0, p1, p2 = pts[i-1], pts[i], pts[(i+1) % n]
            if (abs(p0[0]-p1[0]) < 1e-3 and abs(p1[0]-p2[0]) < 1e-3) or (abs(p0[1]-p1[1]) < 1e-3 and abs(p1[1]-p2[1]) < 1e-3):
                pts = pts[:i] + pts[i+1:]
                changed = True
                break
    if area2(pts) < 0:      # y-down: positive = clockwise on screen
        pts = pts[::-1]
    # start: min y, then min x among vertices with horizontal outgoing edge
    n = len(pts)
    cands = [i for i in range(n) if abs(pts[i][1]-pts[(i+1) % n][1]) < 1e-3]
    s = min(cands, key=lambda i: (round(pts[i][1], 2), pts[i][0]))
    return pts[s:] + pts[:s]

def build():
    out = {}
    for k, (d, a, b, c, dd, tx, ty) in RAW.items():
        loc = dedupe(parse(d))
        pts = [(a*x + b*y + tx, c*x + dd*y + ty) for x, y in loc]
        pts = [(round(x, 2), round(y, 2)) for x, y in pts]
        out[k] = canon(pts)
    return out

