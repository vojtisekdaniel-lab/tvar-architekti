import re

def parse(d):
    pts = [(float(a), float(b)) for a, b in re.findall(r'[ML]\s*([-\d.e+]+)\s+([-\d.e+]+)', d)]
    return pts

def dedupe(pts):
    out = []
    for p in pts:
        if not out or abs(p[0]-out[-1][0]) > 1e-3 or abs(p[1]-out[-1][1]) > 1e-3:
            out.append(p)
    if len(out) > 1 and abs(out[0][0]-out[-1][0]) < 1e-3 and abs(out[0][1]-out[-1][1]) < 1e-3:
        out.pop()
    return out

